"""Google Gemini API service for text, chat, multimodal reasoning, and structured output."""

import json
import logging
from typing import Any, Dict, List, Optional
import google.generativeai as genai
from google.api_core.exceptions import GoogleAPIError, ResourceExhausted, InvalidArgument
from app.core.config import settings

logger = logging.getLogger(__name__)


class GeminiService:
    """Wrapper around Google Gemini Generative AI SDK."""

    def __init__(self):
        self.api_key = settings.GEMINI_API_KEY
        # Check if a real key is provided rather than empty or placeholder
        is_placeholder = not self.api_key or self.api_key.strip().lower() in [
            "",
            "your-gemini-api-key-here",
            "your_gemini_api_key_here",
            "your_api_key_here",
            "changeme",
        ]
        self.is_configured = not is_placeholder
        if self.is_configured:
            genai.configure(api_key=self.api_key)
            logger.info("GeminiService initialized with API key.")
        else:
            logger.warning(
                "GEMINI_API_KEY is not configured or using placeholder. Real API calls will return configuration guidance."
            )

    def is_available(self) -> bool:
        """Check if Gemini API is configured and operational."""
        return self.is_configured

    def _get_model(
        self,
        model_name: Optional[str] = None,
        system_instruction: Optional[str] = None,
        temperature: Optional[float] = 0.7,
        max_output_tokens: Optional[int] = 2048,
        response_mime_type: Optional[str] = None,
    ) -> genai.GenerativeModel:
        """Helper to get a GenerativeModel instance with generation config."""
        selected_model = model_name or settings.DEFAULT_MODEL

        gen_config = {
            "temperature": temperature if temperature is not None else 0.7,
            "max_output_tokens": max_output_tokens if max_output_tokens is not None else 2048,
        }
        if response_mime_type:
            gen_config["response_mime_type"] = response_mime_type

        return genai.GenerativeModel(
            model_name=selected_model,
            generation_config=gen_config,
            system_instruction=system_instruction if system_instruction else None,
        )

    async def generate_text(
        self,
        prompt: str,
        model_name: Optional[str] = None,
        system_instruction: Optional[str] = None,
        temperature: Optional[float] = 0.7,
        max_tokens: Optional[int] = 2048,
    ) -> str:
        """Generate response for a single prompt."""
        if not self.is_configured:
            return (
                "Gemini API key is not configured on the backend. "
                "Please configure GEMINI_API_KEY in backend/.env to enable live generation."
            )

        try:
            model = self._get_model(
                model_name=model_name,
                system_instruction=system_instruction,
                temperature=temperature,
                max_output_tokens=max_tokens,
            )
            response = model.generate_content(prompt)
            if response and response.text:
                return response.text.strip()
            return "No response generated by the model."
        except ResourceExhausted as e:
            logger.error(f"Gemini quota/rate limit exceeded: {e}")
            raise RuntimeError("Gemini rate limit exceeded. Please wait a moment before retrying.")
        except InvalidArgument as e:
            logger.error(f"Invalid argument to Gemini API: {e}")
            raise ValueError(f"Invalid request parameters for Gemini: {str(e)}")
        except GoogleAPIError as e:
            logger.error(f"Gemini API error: {e}")
            raise RuntimeError(f"Gemini service error: {str(e)}")
        except Exception as e:
            logger.error(f"Unexpected error in Gemini generation: {e}")
            raise RuntimeError(f"Generation failed: {str(e)}")

    async def chat(
        self,
        messages: List[Dict[str, str]],
        model_name: Optional[str] = None,
        system_instruction: Optional[str] = None,
        temperature: Optional[float] = 0.7,
        max_tokens: Optional[int] = 2048,
    ) -> str:
        """Multi-turn conversation generation."""
        if not self.is_configured:
            last_user_msg = ""
            for m in reversed(messages):
                if m.get("role") == "user":
                    last_user_msg = m.get("content", "").strip()
                    break

            return (
                f"### Welcome to **DARZFUSION AI**!\n\n"
                f"I received your inquiry: *\"{last_user_msg}\"*\n\n"
                f"**DARZFUSION AI** is your next-generation multimodal Generative AI workspace built on the Google Gemini ecosystem. Here is an overview of my core architecture and operational modules:\n\n"
                f"1. **💬 Multimodal AI Chat & Reasoning**\n"
                f"   - Powered by **Gemini 2.5 Flash** and **1.5 Pro** architectures.\n"
                f"   - High-throughput streaming, contextual awareness, and multi-turn dialogue memory.\n\n"
                f"2. **📄 Document Intelligence & RAG Engine**\n"
                f"   - PDF/text semantic chunking with **ChromaDB vector store**.\n"
                f"   - Dense vector retrieval with similarity ranking and grounded citations.\n\n"
                f"3. **🌐 Real-Time Web Research & Grounding**\n"
                f"   - Live autonomous web query orchestration via **DuckDuckGo/Tavily**.\n"
                f"   - Automatic citation extraction and synthesis.\n\n"
                f"4. **👁️ Visual Question Answering & Audio Transcriptions**\n"
                f"   - High-resolution visual analysis and OCR.\n"
                f"   - Audio transcription, key-point extraction, and study summaries.\n\n"
                f"5. **🧪 Prompt Engineering Lab & Study Suite**\n"
                f"   - Interactive side-by-side comparison of Zero-Shot, Few-Shot, and Chain-of-Thought prompts.\n"
                f"   - Automated flashcard and quiz generation for rapid knowledge acquisition.\n\n"
                f"```python\n"
                f"# DARZFUSION AI Core Integration\n"
                f"from app.services.gemini_service import gemini_service\n"
                f"\n"
                f"response = await gemini_service.generate_text(\n"
                f"    prompt=\"{last_user_msg}\",\n"
                f"    model_name=\"gemini-2.5-flash\"\n"
                f")\n"
                f"```\n\n"
                f"> **System Status**: Dual-routed API active at `/api/v1` and `/api`. To connect direct live cloud inference keys, add your `GEMINI_API_KEY` to `backend/.env`."
            )

        try:
            model = self._get_model(
                model_name=model_name,
                system_instruction=system_instruction,
                temperature=temperature,
                max_output_tokens=max_tokens,
            )

            # Format history for Gemini chat
            # Gemini expects [{'role': 'user'|'model', 'parts': [content]}]
            history = []
            current_message = ""

            for i, msg in enumerate(messages):
                role = "user" if msg.get("role") == "user" else "model"
                content = msg.get("content", "")

                # If this is the last message and it's from the user, keep it to send via send_message
                if i == len(messages) - 1 and role == "user":
                    current_message = content
                else:
                    history.append({"role": role, "parts": [content]})

            chat_session = model.start_chat(history=history)
            response = chat_session.send_message(current_message or "Hello")

            if response and response.text:
                return response.text.strip()
            return "No response generated by the model."
        except ResourceExhausted:
            raise RuntimeError("Gemini rate limit reached. Please try again in a few moments.")
        except Exception as e:
            logger.error(f"Gemini chat error: {e}")
            raise RuntimeError(f"Chat generation error: {str(e)}")

    async def generate_multimodal(
        self,
        prompt: str,
        media_parts: List[Dict[str, Any]],
        model_name: Optional[str] = None,
        system_instruction: Optional[str] = None,
    ) -> str:
        """Multimodal generation for images and audio files."""
        if not self.is_configured:
            return (
                "Gemini API key is not configured on the backend. "
                "Add GEMINI_API_KEY to backend/.env to analyze images and audio."
            )

        try:
            model = self._get_model(
                model_name=model_name,
                system_instruction=system_instruction,
            )

            # Build parts array: [media_part_1, media_part_2, ..., prompt]
            parts: List[Any] = []
            for part in media_parts:
                if "mime_type" in part and "data" in part:
                    parts.append({"mime_type": part["mime_type"], "data": part["data"]})

            parts.append(prompt)
            response = model.generate_content(parts)

            if response and response.text:
                return response.text.strip()
            return "No response generated for the uploaded media."
        except Exception as e:
            logger.error(f"Gemini multimodal error: {e}")
            raise RuntimeError(f"Multimodal processing error: {str(e)}")

    async def generate_json(
        self,
        prompt: str,
        system_instruction: Optional[str] = None,
        model_name: Optional[str] = None,
    ) -> Dict[str, Any]:
        """Generate structured JSON and validate model output."""
        if not self.is_configured:
            return {"error": "GEMINI_API_KEY not configured"}

        try:
            model = self._get_model(
                model_name=model_name,
                system_instruction=system_instruction,
                response_mime_type="application/json",
            )
            response = model.generate_content(prompt)
            text = response.text.strip() if response and response.text else "{}"

            # Clean Markdown code fences if model enclosed in ```json ... ```
            if text.startswith("```"):
                lines = text.split("\n")
                if lines[0].startswith("```"):
                    lines = lines[1:]
                if lines and lines[-1].startswith("```"):
                    lines = lines[:-1]
                text = "\n".join(lines).strip()

            return json.loads(text)
        except json.JSONDecodeError as e:
            logger.error(f"Failed to decode model JSON: {e}")
            raise ValueError("Model produced malformed JSON output.")
        except Exception as e:
            logger.error(f"Gemini JSON generation error: {e}")
            raise RuntimeError(f"Structured generation error: {str(e)}")


gemini_service = GeminiService()
